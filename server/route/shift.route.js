import { Router } from 'express';
import auth from '../middleware/auth.js';
import requireRole from '../middleware/roleAuth.js';
import { staffOnly } from '../middleware/shiftAccess.js';
import * as controller from '../controllers/shift.controller.js';
const router = Router();
const manager = requireRole('MANAGER');
router.use(auth, staffOnly);
router.post('/create', manager, controller.createShift);
router.get('/date', controller.getShiftsByDate);
router.get('/employee/:employeeId', controller.getShiftsByEmployee);
router.put('/update/:id', manager, controller.updateShift);
router.delete('/delete/:id', manager, controller.deleteShift);
router.post('/assign', manager, controller.assignStaffToShift);
router.post('/unassign', manager, controller.unassignStaff);
router.post('/copy-week', manager, controller.copyShifts);
router.get('/requests', controller.getRequests);
router.post('/requests/:id/respond', controller.respondToRequest);
router.get('/notifications', controller.getNotifications);
router.post('/notifications/:id/read', controller.readNotification);
router.post('/:id/publish', manager, controller.publishShift);
router.post('/:id/cancel', manager, controller.deleteShift);
router.post('/:id/confirm', controller.confirmShift);
router.post('/:id/finish', manager, controller.finishShift);
router.post('/:id/review', manager, controller.reviewShift);
router.get('/:id/replacements', controller.getCandidates);
router.post('/:id/requests', controller.createRequest);
export default router;
